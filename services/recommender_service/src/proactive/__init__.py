# proactive – Micro-Moment Context & Proactivity Handler
#
# Detects user state (location, time, activity) and triggers relevant
# push recommendations.  Six distinct micro-moment contexts are recognised:
#
#   1. mealtime_proximity  – meal-hour near a food zone
#   2. weather_alert        – adverse weather approaching
#   3. crowd_surge          – current/planned POI is overcrowded
#   4. golden_hour          – sunset/sunrise scenic opportunity
#   5. transit_window       – idle gap between planned activities
#   6. cultural_event       – nearby cultural event happening now
